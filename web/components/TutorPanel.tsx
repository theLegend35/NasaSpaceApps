"use client";

// AI overview and tutor (design doc Feature 12): grounded in a fact sheet,
// citation chips link to facts, every number checked server side.

import { useState } from "react";
import { PaperPlaneRight } from "@phosphor-icons/react";
import { apiPost, ApiError } from "@/lib/api";
import type { TutorResponse } from "@/lib/types";

const SUGGESTED = ["Summarize this object", "Why is this a brown dwarf?", "Why can't I see it move in six months?"];

type Ctx = { targetQuery?: string | null; ra?: number; dec?: number; fov?: number; detector?: string; sourceId?: string | null };

export default function TutorPanel({ ctx }: { ctx: Ctx }) {
  const [q, setQ] = useState("");
  const [level, setLevel] = useState<"student" | "volunteer" | "astronomer">("student");
  const [busy, setBusy] = useState(false);
  const [res, setRes] = useState<TutorResponse | null>(null);
  const [err, setErr] = useState<string | null>(null);

  const ask = async (question: string) => {
    setBusy(true); setErr(null);
    try {
      setRes(await apiPost<TutorResponse>("/tutor", { question, level, ...ctx, sourceId: ctx.sourceId ?? undefined, targetQuery: ctx.targetQuery ?? undefined }));
    } catch (e) {
      setErr(e instanceof ApiError ? e.message : "The tutor couldn't answer right now.");
    } finally { setBusy(false); }
  };

  const withCites = (text: string) =>
    text.split(/(\[F\d+\])/g).map((part, i) => {
      const m = part.match(/^\[(F\d+)\]$/);
      return m ? <a key={i} className="cite" href={`#fact-${m[1]}`}>{m[1]}</a> : <span key={i}>{part}</span>;
    });

  return (
    <div className="col" style={{ gap: "var(--space-3)" }}>
      <div className="row wrap">
        <div className="seg" aria-label="Reading level">
          {(["student", "volunteer", "astronomer"] as const).map((l) => (
            <label key={l} className="seg-opt"><input type="radio" name="level" checked={level === l} onChange={() => setLevel(l)} />{l[0].toUpperCase() + l.slice(1)}</label>
          ))}
        </div>
      </div>
      <div className="row wrap">
        {SUGGESTED.map((s) => <button key={s} className="btn btn-secondary small" disabled={busy} onClick={() => { setQ(s); ask(s); }}>{s}</button>)}
      </div>
      <form className="row" onSubmit={(e) => { e.preventDefault(); if (q.trim()) ask(q); }}>
        <label className="sr-only" htmlFor="tutor-q">Ask the tutor</label>
        <input id="tutor-q" className="input" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask about this object" maxLength={500} />
        <button className="btn btn-primary" disabled={busy || !q.trim()}><PaperPlaneRight />Ask</button>
      </form>
      {busy && <span className="small muted">Thinking…</span>}
      {err && <span className="small" style={{ color: "var(--color-accent-300)" }}>{err}</span>}
      {res && (
        <div className="card" style={{ gap: "var(--space-3)", padding: "var(--space-4)" }}>
          {res.answer ? <p style={{ margin: 0, fontSize: 14 }}>{withCites(res.answer)}</p>
            : <p style={{ margin: 0, fontSize: 14 }}>{res.offline ?? "No answer."} Here are the facts we have.</p>}
          {res.droppedSentences > 0 && <span className="small muted">{res.droppedSentences} sentence{res.droppedSentences > 1 ? "s" : ""} removed because they used numbers not in the facts.</span>}
          <ol className="small" style={{ margin: 0, paddingLeft: 18, color: "var(--color-neutral-300)" }}>
            {res.facts.map((f) => (
              <li key={f.id} id={`fact-${f.id}`} value={Number(f.id.slice(1))}>
                {f.text} <span className="muted">({f.url ? <a href={f.url} target="_blank" rel="noreferrer">{f.source}</a> : f.source})</span>
              </li>
            ))}
          </ol>
          <span className="small muted">{res.disclaimer ?? "Answer generated by AI from the facts listed; check the sources."}{res.model ? ` Model: ${res.model}.` : ""}</span>
        </div>
      )}
    </div>
  );
}
